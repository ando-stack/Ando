import { execFileSync, spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { getConfig, r } from "../core/config.ts";
import type { ScenePlan } from "../core/types.ts";
import { SR, buildSfxBed, synthMusic, type SfxType } from "./synth.ts";
import { readWav, writeWav } from "./wav.ts";

const AUDIO_EXT = /\.(wav|mp3|ogg|flac|m4a|aac)$/i;

function ff(args: string[]) {
  return execFileSync("ffmpeg", ["-hide_banner", "-y", "-loglevel", "error", ...args], { maxBuffer: 64 * 1024 * 1024 }).toString();
}

function libraryFiles(dir: string): string[] {
  const d = path.isAbsolute(dir) ? dir : r(dir);
  if (!fs.existsSync(d)) return [];
  return fs.readdirSync(d).filter((f) => AUDIO_EXT.test(f)).map((f) => path.join(d, f));
}

/**
 * Music bed: a licensed track from assets/music (user-provided, rotated per video),
 * otherwise an original synthesized track. Returns provenance for the metadata.
 */
export function prepareMusic(outFile: string, durationSec: number, seed: number): { source: string; license: string } {
  const cfg = getConfig().music;
  const lib = cfg.source === "synth" ? [] : libraryFiles(getConfig().assets.musicDir);
  if (lib.length) {
    const pick = lib[seed % lib.length];
    const fadeOut = Math.max(0, durationSec - 1.5);
    ff(["-stream_loop", "-1", "-i", pick, "-t", String(durationSec + 0.5), "-af", `afade=t=in:d=0.8,afade=t=out:st=${fadeOut}:d=1.5`, "-ar", String(SR), "-ac", "2", "-c:a", "pcm_s16le", outFile]);
    let license = "user-provided (see assets/music)";
    try {
      license = (JSON.parse(fs.readFileSync(pick + ".json", "utf8")) as { license?: string }).license ?? license;
    } catch { /* no sidecar */ }
    return { source: path.basename(pick), license };
  }
  writeWav(outFile, synthMusic(durationSec, { bpm: cfg.bpm, seed }), SR);
  return { source: "original synthesized score", license: "Original (generated by GTA VI Shorts Factory) — no third-party rights" };
}

/** SFX: user-provided files named like "whoosh*.wav" in assets/sfx override the synthesized ones. */
export function prepareSfx(outFile: string, plan: ScenePlan): { source: string } {
  const lib = libraryFiles(getConfig().assets.sfxDir);
  const sources: Partial<Record<SfxType, Float32Array[]>> = {};
  for (const type of ["whoosh", "impact", "riser", "reveal", "tick"] as SfxType[]) {
    const f = lib.find((x) => path.basename(x).toLowerCase().startsWith(type));
    if (!f) continue;
    const tmp = outFile + `.${type}.wav`;
    ff(["-i", f, "-ar", String(SR), "-ac", "2", "-c:a", "pcm_s16le", tmp]);
    sources[type] = readWav(tmp).channels;
    fs.rmSync(tmp, { force: true });
  }
  writeWav(outFile, buildSfxBed(plan.durationSec, plan.sfx, sources), SR);
  return { source: Object.keys(sources).length ? `library: ${Object.keys(sources).join(", ")}; rest synthesized` : "original synthesized SFX" };
}

/**
 * Final mix: narration on top, music ducked by a sidechain compressor keyed from the
 * narration, SFX bed, then two-pass EBU R128 loudness normalization + true-peak limit.
 */
export function mixAudio(opts: { voice: string; music?: string; sfx?: string; out: string; durationSec: number }) {
  const cfg = getConfig();
  const inputs = ["-i", opts.voice];
  const parts: string[] = [`[0:a]aformat=sample_rates=${SR}:channel_layouts=mono,pan=stereo|c0=c0|c1=c0,asplit=2[vo][key]`];
  const mixIn = ["[vo]"];
  let idx = 1;
  if (opts.music) {
    inputs.push("-i", opts.music);
    const ratio = Math.max(2, Math.min(20, Math.pow(10, -cfg.music.duckDb / 20) * 2));
    parts.push(`[${idx}:a]aformat=sample_rates=${SR}:channel_layouts=stereo,volume=${cfg.music.volumeDb}dB[mus]`);
    parts.push(`[mus][key]sidechaincompress=threshold=0.015:ratio=${ratio.toFixed(1)}:attack=15:release=420:makeup=1[duck]`);
    mixIn.push("[duck]");
    idx++;
  } else parts.push(`[key]anullsink`);
  if (opts.sfx) {
    inputs.push("-i", opts.sfx);
    parts.push(`[${idx}:a]aformat=sample_rates=${SR}:channel_layouts=stereo,volume=${cfg.sfx.volumeDb}dB[fx]`);
    mixIn.push("[fx]");
    idx++;
  }
  parts.push(`${mixIn.join("")}amix=inputs=${mixIn.length}:normalize=0:duration=first,atrim=0:${opts.durationSec.toFixed(3)}[pre]`);
  const graph = parts.join(";");
  const pre = opts.out.replace(/\.wav$/, ".pre.wav");
  ff([...inputs, "-filter_complex", graph, "-map", "[pre]", "-ar", String(SR), "-c:a", "pcm_s16le", pre]);

  // Pass 1: measure.
  const I = cfg.audio.targetLufs, TP = cfg.audio.truePeak;
  const stderr = runCapture(["-hide_banner", "-i", pre, "-af", `loudnorm=I=${I}:TP=${TP}:LRA=11:print_format=json`, "-f", "null", "-"]);
  const json = JSON.parse(stderr.slice(stderr.lastIndexOf("{"), stderr.lastIndexOf("}") + 1)) as Record<string, string>;
  // Pass 2: apply (linear mode keeps dynamics), then a brickwall limiter as a safety net.
  const limit = Math.pow(10, TP / 20).toFixed(3);
  ff([
    "-i", pre,
    "-af",
    `loudnorm=I=${I}:TP=${TP}:LRA=11:measured_I=${json.input_i}:measured_TP=${json.input_tp}:measured_LRA=${json.input_lra}:measured_thresh=${json.input_thresh}:offset=${json.target_offset}:linear=true,alimiter=limit=${limit}:level=false,aresample=${SR}`,
    "-ar", String(SR), "-c:a", "pcm_s16le", opts.out,
  ]);
  fs.rmSync(pre, { force: true });
  return { measuredInput: json };
}

/** Run ffmpeg and return stderr (where filters print their reports). */
export function runCapture(args: string[]): string {
  const res = spawnSync("ffmpeg", args, { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
  if (res.error) throw res.error;
  return res.stderr ?? "";
}
